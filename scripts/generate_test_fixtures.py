"""Generate synthetic test fixtures for plate detector evaluation.

Creates programmatic images with known plate-like regions and writes
bounding-box ground truth to a JSON file.  No real vehicle images are
used — all fixtures are synthetic to guarantee legal reuse.

Usage:
    python scripts/generate_test_fixtures.py
    python scripts/generate_test_fixtures.py --output sample-data/evaluation
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    sys.exit("Pillow is required: pip install Pillow")


def _draw_plate(
    draw: ImageDraw.ImageDraw,
    x1: int,
    y1: int,
    width: int,
    height: int,
    bg_color: str,
    text_color: str,
    text: str,
) -> dict:
    """Draw a plate-like rectangle and return bounding-box ground truth."""

    x2, y2 = x1 + width, y1 + height
    draw.rectangle([x1, y1, x2, y2], fill=bg_color, outline="black", width=2)

    # Center text inside the plate rectangle.
    try:
        font = ImageFont.truetype("arial.ttf", max(12, height // 3))
    except OSError:
        font = ImageFont.load_default()

    text_bbox = draw.textbbox((0, 0), text, font=font)
    tw, th = text_bbox[2] - text_bbox[0], text_bbox[3] - text_bbox[1]
    tx = x1 + (width - tw) // 2
    ty = y1 + (height - th) // 2
    draw.text((tx, ty), text, fill=text_color, font=font)

    return {"x1": x1, "y1": y1, "x2": x2, "y2": y2, "text": text}


def generate_synthetic_plate_white(output_dir: Path) -> dict:
    """White plate with black text on a neutral background."""

    img = Image.new("RGB", (640, 480), color=(120, 130, 140))
    draw = ImageDraw.Draw(img)
    # Vehicle body
    draw.rectangle([100, 150, 540, 430], fill=(60, 60, 80))
    bbox = _draw_plate(draw, 220, 320, 200, 50, "white", "black", "YGN 5A-1234")
    path = output_dir / "synthetic_plate_white.png"
    img.save(path)
    return {
        "file": path.name,
        "width": img.width,
        "height": img.height,
        "expected_detections": 1,
        "bounding_boxes": [bbox],
        "source": "project-generated by scripts/generate_test_fixtures.py",
        "license": "project educational use; see sample-data/evaluation/README.md",
    }


