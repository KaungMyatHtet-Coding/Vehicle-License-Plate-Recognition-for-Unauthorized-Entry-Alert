def generate_synthetic_no_plate(output_dir: Path) -> dict:
    """Plain scene with no plate-like region."""

    img = Image.new("RGB", (640, 480), color=(100, 150, 200))
    draw = ImageDraw.Draw(img)
    # Trees / nature — no rectangles
    draw.ellipse([50, 100, 250, 350], fill=(30, 120, 50))
    draw.ellipse([300, 80, 550, 380], fill=(40, 130, 60))
    draw.rectangle([0, 400, 640, 480], fill=(80, 60, 40))
    path = output_dir / "synthetic_no_plate.png"
    img.save(path)
    return {
        "file": path.name,
        "width": img.width,
        "height": img.height,
        "expected_detections": 0,
        "bounding_boxes": [],
        "source": "project-generated by scripts/generate_test_fixtures.py",
        "license": "project educational use; see sample-data/evaluation/README.md",
    }


def generate_synthetic_multi_plate(output_dir: Path) -> dict:
    """Two vehicles / two plate-like regions."""

    img = Image.new("RGB", (800, 480), color=(130, 130, 130))
    draw = ImageDraw.Draw(img)
    # Vehicle 1 (left)
    draw.rectangle([30, 150, 360, 430], fill=(70, 30, 30))
    bbox1 = _draw_plate(draw, 120, 340, 180, 45, "white", "black", "SGN 1C-9012")
    # Vehicle 2 (right)
    draw.rectangle([420, 150, 770, 430], fill=(30, 30, 70))
    bbox2 = _draw_plate(draw, 520, 340, 180, 45, "white", "black", "NPT 2D-3456")
    path = output_dir / "synthetic_multi_plate.png"
    img.save(path)
    return {
        "file": path.name,
        "width": img.width,
        "height": img.height,
        "expected_detections": 2,
        "bounding_boxes": [bbox1, bbox2],
        "source": "project-generated by scripts/generate_test_fixtures.py",
        "license": "project educational use; see sample-data/evaluation/README.md",
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate synthetic plate detection test fixtures."
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("sample-data/evaluation"),
        help="Directory to write fixture images and ground truth (default: sample-data/evaluation)",
    )
    args = parser.parse_args()

    output_dir: Path = args.output
    output_dir.mkdir(parents=True, exist_ok=True)

    ground_truth: list[dict] = []
    generators = [
        generate_synthetic_plate_white,
        generate_synthetic_plate_yellow,
        generate_synthetic_no_plate,
        generate_synthetic_multi_plate,
    ]

    for gen in generators:
        entry = gen(output_dir)
        ground_truth.append(entry)
        status = f"{entry['expected_detections']} detection(s)"
        print(f"  Created {entry['file']:40s} [{status}]")

    gt_path = output_dir / "ground_truth.json"
    gt_path.write_text(json.dumps(ground_truth, indent=2), encoding="utf-8")
    print(f"\n  Ground truth written to {gt_path}")
    print(f"  Total fixtures: {len(ground_truth)}")


if __name__ == "__main__":
    main()
